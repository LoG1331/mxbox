#!/usr/bin/env node

import { randomBytes } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_ENV_PATH = path.join(ROOT_DIR, '.env');

function randomSecret(bytes = 32) {
    return randomBytes(bytes).toString('base64url');
}

function randomPassword(length = 24) {
    const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789!@#$%^&*_-+=';
    let value = '';
    while (value.length < length) {
        const index = randomBytes(1)[0] % alphabet.length;
        value += alphabet[index];
    }

    return value;
}

function parseEnvDocument(text) {
    const lines = String(text || '').split(/\r?\n/);
    const map = new Map();

    for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) {
            continue;
        }

        const separatorIndex = line.indexOf('=');
        if (separatorIndex <= 0) {
            continue;
        }

        const key = line.slice(0, separatorIndex).trim();
        const rawValue = line.slice(separatorIndex + 1).trim();
        const value = rawValue.replace(/^"(.*)"$/, '$1');
        map.set(key, value);
    }

    return map;
}

function buildEnvDocument(values) {
    return [
        '# Generated by scripts/generate-env-secrets.mjs',
        '# Review CORS_ALLOWED_ORIGINS / PORT / DB path before production startup.',
        '',
        'NODE_ENV=production',
        `HOST=${values.HOST}`,
        `PORT=${values.PORT}`,
        `TRUST_PROXY=${values.TRUST_PROXY}`,
        `NEW_SERVER_SQLITE_PATH=${values.NEW_SERVER_SQLITE_PATH}`,
        '',
        `INBOUND_AUTH_TOKEN=${values.INBOUND_AUTH_TOKEN}`,
        `AUTH_JWT_SECRET=${values.AUTH_JWT_SECRET}`,
        `API_KEY_PEPPER=${values.API_KEY_PEPPER}`,
        '',
        `BOOTSTRAP_ADMIN_USERNAME=${values.BOOTSTRAP_ADMIN_USERNAME}`,
        `BOOTSTRAP_ADMIN_PASSWORD=${values.BOOTSTRAP_ADMIN_PASSWORD}`,
        '',
        `CORS_ALLOWED_ORIGINS=${values.CORS_ALLOWED_ORIGINS}`,
        `AUTO_CREATE_DOMAINS_ON_INGEST=${values.AUTO_CREATE_DOMAINS_ON_INGEST}`,
        `STORE_RAW_MIME=${values.STORE_RAW_MIME}`,
        `RAW_MIME_RETENTION_DAYS=${values.RAW_MIME_RETENTION_DAYS}`,
        `MAINTENANCE_PRUNE_INTERVAL_MS=${values.MAINTENANCE_PRUNE_INTERVAL_MS}`,
        ''
    ].join('\n');
}

async function main() {
    const envPath = process.argv[2]
        ? path.resolve(process.cwd(), process.argv[2])
        : DEFAULT_ENV_PATH;

    let currentText = '';
    try {
        currentText = await readFile(envPath, 'utf8');
    } catch {
        currentText = '';
    }

    const current = parseEnvDocument(currentText);
    const values = {
        HOST: current.get('HOST') || '0.0.0.0',
        PORT: current.get('PORT') || '3001',
        TRUST_PROXY: current.get('TRUST_PROXY') || '1',
        NEW_SERVER_SQLITE_PATH: current.get('NEW_SERVER_SQLITE_PATH') || './data/new-server.sqlite',
        INBOUND_AUTH_TOKEN: current.get('INBOUND_AUTH_TOKEN') || randomSecret(36),
        AUTH_JWT_SECRET: current.get('AUTH_JWT_SECRET') || randomSecret(48),
        API_KEY_PEPPER: current.get('API_KEY_PEPPER') || randomSecret(48),
        BOOTSTRAP_ADMIN_USERNAME: current.get('BOOTSTRAP_ADMIN_USERNAME') || 'admin',
        BOOTSTRAP_ADMIN_PASSWORD: current.get('BOOTSTRAP_ADMIN_PASSWORD') || randomPassword(24),
        CORS_ALLOWED_ORIGINS: current.get('CORS_ALLOWED_ORIGINS') || 'https://app.example.com',
        AUTO_CREATE_DOMAINS_ON_INGEST: current.get('AUTO_CREATE_DOMAINS_ON_INGEST') || 'false',
        STORE_RAW_MIME: current.get('STORE_RAW_MIME') || 'true',
        RAW_MIME_RETENTION_DAYS: current.get('RAW_MIME_RETENTION_DAYS') || '7',
        MAINTENANCE_PRUNE_INTERVAL_MS: current.get('MAINTENANCE_PRUNE_INTERVAL_MS') || '900000'
    };

    await mkdir(path.dirname(envPath), { recursive: true });
    await writeFile(envPath, buildEnvDocument(values), 'utf8');

    console.log(`Wrote ${envPath}`);
    console.log(`Bootstrap admin username: ${values.BOOTSTRAP_ADMIN_USERNAME}`);
    console.log(`Bootstrap admin password: ${values.BOOTSTRAP_ADMIN_PASSWORD}`);
}

await main();
